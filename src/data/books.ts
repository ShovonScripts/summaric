export const PUBLISHED_BOOKS = BOOKS.filter(
  (book) => book.status === "published",
).sort((a, b) => b.addedAt.localeCompare(a.addedAt));

export const FEATURED_BOOK =
  PUBLISHED_BOOKS.find((book) => book.featured) ?? PUBLISHED_BOOKS[0];

export function getBookBySlug(slug: string) {
  return BOOKS.find((book) => book.slug === slug);
}

export function getPublishedBookBySlug(slug: string) {
  return PUBLISHED_BOOKS.find((book) => book.slug === slug);
}

export function countBooksByCategory(category: CategorySlug) {
  return PUBLISHED_BOOKS.filter((book) => book.category === category).length;
}
